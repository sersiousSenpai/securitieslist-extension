// Builds the offline seed from seed/seed.json:
//   extension/data/seed-index.json   (same shape as the flagged_index view)
//   extension/data/seed-events.json  (same shape as the events_by_ticker view)
//   supabase/seed.sql                (rows for the real tables)
// Run: node scripts/build-seed.mjs

import { readFile, writeFile } from "node:fs/promises";
import { copyFile } from "node:fs/promises";
import { urlHash } from "../extension/src/canonical.js";

const root = new URL("..", import.meta.url);

// Edge functions can't import from outside supabase/functions, so they get a
// copy of the one canonicalization module. tests/ checks the copies match.
await copyFile(new URL("extension/src/canonical.js", root), new URL("supabase/functions/_shared/canonical.js", root));
const seed = JSON.parse(await readFile(new URL("seed/seed.json", root), "utf8"));

const CLOSED = new Set(["dismissed", "settled", "closed"]);
const SEVERITY_RANK = { low: 1, medium: 2, high: 3 };
const DEMO_BASE = "http://localhost:8000/demo/wire";
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const now = new Date().toISOString();

// Expand investigation events into one release URL per firm, so "1 of N"
// has a realistic N. The first firm's page exists under demo/wire/.
for (const e of seed.events) {
  if (!e.source_urls_from_demo) continue;
  const firms = seed.firms.slice(0, e.firms_from_seed);
  e.firms = firms;
  e.source_urls = firms.map((f) => `${DEMO_BASE}/${e.ticker.toLowerCase()}-${slug(f)}.html`);
  delete e.source_urls_from_demo;
  delete e.firms_from_seed;
}
for (const e of seed.events) {
  e.source_url_hashes = await Promise.all(e.source_urls.map(urlHash));
  e.firms ??= [];
  e.updated_at = now;
  e.first_seen_at = now;
}

const companies = new Map(seed.companies.map((c) => [c.ticker, c]));

const index = seed.companies
  .map((c) => {
    const evs = seed.events.filter((e) => e.ticker === c.ticker);
    const open = evs.filter((e) => !CLOSED.has(e.status));
    if (!open.length) return null;
    const max = open.reduce((m, e) => (SEVERITY_RANK[e.severity] > SEVERITY_RANK[m] ? e.severity : m), "low");
    return {
      ticker: c.ticker,
      exchange: c.exchange,
      company: c.name,
      names: [c.name, ...c.aliases],
      count: open.length,
      max_severity: max,
      updated_at: now,
      investigations: open
        .filter((e) => e.category === "investigation")
        .map((e) => ({
          event_id: e.id,
          firms: e.firms,
          release_count: e.source_urls.length,
          release_hashes: e.source_url_hashes,
        })),
    };
  })
  .filter(Boolean);

const events = seed.events.map((e) => ({
  id: e.id,
  ticker: e.ticker,
  company: companies.get(e.ticker).name,
  category: e.category,
  status: e.status,
  event_date: e.event_date,
  severity: e.severity,
  title: e.title,
  summary: e.summary,
  alleged_conduct: e.alleged_conduct ?? null,
  source_urls: e.source_urls,
  firms: e.firms,
  class_period_start: e.class_period?.start ?? null,
  class_period_end: e.class_period?.end ?? null,
  lead_plaintiff_deadline: e.lead_plaintiff_deadline ?? null,
  court: e.court ?? null,
  case_number: e.case_number ?? null,
  first_seen_at: e.first_seen_at,
  updated_at: e.updated_at,
}));

await writeFile(
  new URL("extension/data/seed-index.json", root),
  JSON.stringify({ demo: true, firms: seed.firms, tickers: index }, null, 2) + "\n",
);
await writeFile(new URL("extension/data/seed-events.json", root), JSON.stringify(events, null, 2) + "\n");

const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(",")}]::text[]`;
const sql = [
  "-- Generated by scripts/build-seed.mjs from seed/seed.json. DEMO DATA: fictional companies.",
  "begin;",
  ...seed.firms.map((f) => `insert into firms (name) values (${q(f)}) on conflict do nothing;`),
  ...seed.companies.map(
    (c) =>
      `insert into companies (ticker, exchange, name, aliases, cik, is_demo) values (${q(c.ticker)}, ${q(c.exchange)}, ${q(c.name)}, ${arr(c.aliases)}, ${q(c.cik)}, true) on conflict (ticker) do nothing;`,
  ),
  ...seed.events.map(
    (e) =>
      `insert into events (id, company_id, category, status, event_date, severity, title, summary, alleged_conduct, source_urls, source_url_hashes, firms, class_period_start, class_period_end, lead_plaintiff_deadline, court, case_number, dedupe_key)
  select ${q(e.id)}, id, ${q(e.category)}, ${q(e.status)}, ${q(e.event_date)}, ${q(e.severity)}, ${q(e.title)}, ${q(e.summary)}, ${q(e.alleged_conduct)}, ${arr(e.source_urls)}, ${arr(e.source_url_hashes)}, ${arr(e.firms)}, ${q(e.class_period?.start)}, ${q(e.class_period?.end)}, ${q(e.lead_plaintiff_deadline)}, ${q(e.court)}, ${q(e.case_number)}, ${q("seed:" + e.id)}
  from companies where ticker = ${q(e.ticker)} on conflict (id) do nothing;`,
  ),
  "commit;",
  "",
].join("\n");
await writeFile(new URL("supabase/seed.sql", root), sql);

console.log(`seed: ${index.length} flagged tickers, ${events.length} events, ${seed.firms.length} firms`);
